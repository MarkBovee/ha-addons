#!/usr/bin/env python3
"""Vendor hems/core/hems into custom_components/hems/engine (a custom integration must be self-contained).

hems/core stays the source of truth: never edit the engine copy. Imports are rewritten from `hems.x` to relative
`.x`, so the same code runs as a package inside the integration. Test-only modules (fakes, replay) stay out.

Usage: python3 scripts/sync_hems_core.py          # write the copy
       python3 scripts/sync_hems_core.py --check  # exit 1 when the copy is stale (used by the tests)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "hems" / "core" / "hems"
DST = ROOT / "custom_components" / "hems" / "engine"
SKIP = {"fakes.py", "replay.py"}
HEADER = '# GENERATED by scripts/sync_hems_core.py from hems/core/hems/{name}; do not edit here.\n'


def vendored(name: str) -> str:
    """Source text of one core module as it must appear in the integration."""
    text = (SRC / name).read_text(encoding="utf-8")
    return HEADER.format(name=name) + re.sub(r"^from hems\.(\w+) import", r"from .\1 import", text, flags=re.MULTILINE)


def expected() -> dict[str, str]:
    """File name -> content for the whole engine package."""
    return {p.name: vendored(p.name) for p in sorted(SRC.glob("*.py")) if p.name not in SKIP}


def stale() -> list[str]:
    """Engine files that differ from what the sync would write (missing, changed or left over)."""
    want = expected()
    have = {p.name: p.read_text(encoding="utf-8") for p in DST.glob("*.py")} if DST.exists() else {}
    return sorted({n for n in want if have.get(n) != want[n]} | (set(have) - set(want)))


def main() -> int:
    """Write (or with --check, only verify) the vendored engine."""
    if "--check" in sys.argv:
        diff = stale()
        print("engine copy is current" if not diff else f"stale engine files: {diff}")
        return 1 if diff else 0
    DST.mkdir(parents=True, exist_ok=True)
    for name in set(p.name for p in DST.glob("*.py")) - set(expected()):
        (DST / name).unlink()
    for name, text in expected().items():
        (DST / name).write_text(text, encoding="utf-8")
    print(f"synced {len(expected())} modules to {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
